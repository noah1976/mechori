export type TranslationKey = keyof typeof ja;
type Dictionary = Record<TranslationKey, string>;

export const dictionaries: Record<SupportedUiLocale, Dictionary> = { ja, en };

export const uiLocaleOptions: ReadonlyArray<{
  value: SupportedUiLocale;
  label: string;
  shortLabel: string;
}> = [
  { value: "ja", label: "日本語", shortLabel: "JA" },
  { value: "en", label: "English", shortLabel: "EN" },
];

export type TranslationValues = Readonly<Record<string, string | number>>;

export function translate(
  locale: SupportedUiLocale,
  key: TranslationKey,
  values?: TranslationValues,
): string {
  const message = dictionaries[locale][key];
  if (!values) return message;
  return message.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (placeholder, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : placeholder,
  );
}

export function formatUiNumber(
  locale: SupportedUiLocale,
  value: number,
  options?: Intl.NumberFormatOptions,
): string {
  return new Intl.NumberFormat(toIntlLocale(locale), options).format(value);
}

export function formatUiDate(
  locale: SupportedUiLocale,
  value: string | number | Date,
  options: Intl.DateTimeFormatOptions = {
    year: "numeric",
    month: "short",
    day: "numeric",
  },
): string {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return typeof value === "string" ? value : "";
  return new Intl.DateTimeFormat(toIntlLocale(locale), options).format(date);
}

function toIntlLocale(locale: SupportedUiLocale): string {
  return locale === "ja" ? "ja-JP" : "en-US";
}
